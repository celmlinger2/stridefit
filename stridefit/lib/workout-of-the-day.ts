/**
 * Deterministic daily quote: changes at midnight with the workout.
 * Seeded from the absolute calendar-day number (days since the Unix epoch,
 * derived from the *local* date key), so the full quote bank cycles with no
 * repeats for ~2 years instead of restarting every January.
 */
export function getDailyQuote(key: string = todayKey()): string {
  const [y, m, d] = key.split("-").map(Number);
  const epochDay = Math.floor(Date.UTC(y, m - 1, d) / 86400000);
  return QUOTES[epochDay % QUOTES.length];
}
